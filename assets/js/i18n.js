const I18n = {
  lang: "en",
  init() {
    let saved = null;
    try { saved = localStorage.getItem("abra.lang"); } catch (e) {}
    const nav = (navigator.language || "en").toLowerCase();
    this.lang = saved === "en" || saved === "id" ? saved : nav.startsWith("id") || nav.startsWith("ms") ? "id" : "en";
    this.apply();
  },
  t(key, vars) {
    const dict = ABRA_I18N[this.lang] || ABRA_I18N.en;
    let s = dict[key] ?? ABRA_I18N.en[key] ?? key;
    if (vars) for (const k in vars) s = s.replaceAll("{" + k + "}", vars[k]);
    return s;
  },
  locale() { return this.lang === "id" ? "id-ID" : "en-US"; },
  set(lang) {
    this.lang = lang;
    try { localStorage.setItem("abra.lang", lang); } catch (e) {}
    this.apply();
  },
  apply(root = document) {
    document.documentElement.lang = this.lang;
    root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = this.t(el.dataset.i18n); });
    root.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = this.t(el.dataset.i18nHtml); });
    root.querySelectorAll("[data-i18n-alt]").forEach(el => { el.alt = this.t(el.dataset.i18nAlt); });
    root.querySelectorAll("[data-i18n-label]").forEach(el => { el.setAttribute("aria-label", this.t(el.dataset.i18nLabel)); });
    document.dispatchEvent(new CustomEvent("abra:lang", { detail: this.lang }));
  }
};
